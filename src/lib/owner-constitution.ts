type Section = { id: string; title: string; text: string };

/** Apartados del texto íntegro («A. PRODUCTO, NO CÓDIGO»…), para dar a cada tarea solo los suyos. */
function sections(text: string, prefix = ""): Section[] {
  const out: Section[] = [];
  const re = /={20,}\n([A-Z])\. ([^\n]+)\n={20,}\n([\s\S]*?)(?=\n={20,}\n[A-Z]\. |\n={20,}\s*$|$)/g;
  for (const m of text.matchAll(re)) out.push({ id: `${prefix}${m[1]}`, title: m[2]!.trim(), text: m[3]!.trim() });
  return out;
}

export const CONSTITUTION_SECTIONS: Section[] = [...sections(CONSTITUTION_TEXT), ...sections(REBUILD_ANNEX_TEXT, "R")];

export type ConstitutionTask = "proyecto" | "replicacion" | "entrega" | "autoconstruccion";

const FOR_TASK: Record<ConstitutionTask, string[]> = {
  // Construir un proyecto: producto, nada a medias, verificación, arquitectura, infraestructura, diseño, seguridad, equipo senior.
  proyecto: ["A", "B", "C", "E", "F", "G", "H", "K", "T"],
  // Replicación funcional: el anexo completo (T–Z) más producto, verificación, seguridad y no prometer de más.
  replicacion: ["A", "B", "C", "K", "RT", "RU", "RX", "RY", "RZ"],
  // Entrega: metadatos, información obligatoria, producto limpio, revisión de rastros de IA y pre-entrega.
  entrega: ["O", "P", "Q", "R", "S"],
  // Autoconstrucción: mejora autónoma y su flujo obligatorio.
  autoconstruccion: ["C", "M", "N", "V"],
};

/** Apartados completos de la Constitución para una tarea (texto del dueño, sin resumir). */
export function constitutionFor(task: ConstitutionTask, extra: string[] = []): string {
  return [`CONSTITUCIÓN DEL DUEÑO — apartados para esta tarea (${task}):`, constitutionSections([...FOR_TASK[task], ...extra])].join("\n\n");
}

/** Los apartados pedidos («A», «C», «RT»…), con su texto íntegro y en el orden pedido. */
export function constitutionSections(ids: string[]): string {
  const picked = ids.map((id) => CONSTITUTION_SECTIONS.find((s) => s.id === id)).filter((s): s is Section => !!s);
  return picked.map((s) => `${s.id.replace(/^R/, "")}. ${s.title}\n${s.text}`).join("\n\n");
}
